"""
Report Module - Standalone HTML / Markdown Report Generator from VortexOSINT JSON outputs
"""

import argparse
import datetime
import html
import json
from pathlib import Path
from typing import Any, Dict, List

from vortexosint.core.banner import print_module_banner
from vortexosint.core.colors import Colors
from vortexosint.core.output import flatten_dict


def _render_html_report(sections: List[Dict[str, Any]], title: str) -> str:
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    cards_html: List[str] = []

    for sec in sections:
        name = html.escape(sec["source"])
        flat = flatten_dict(sec["data"])
        rows = "\n".join(
            f"<tr><td class='k'>{html.escape(str(k))}</td>"
            f"<td class='v'>{html.escape(str(v))}</td></tr>"
            for k, v in flat.items()
        )
        cards_html.append(
            f"<section class='card'>"
            f"<h2>{name} <span class='badge'>{len(flat)} fields</span></h2>"
            f"<table><thead><tr><th>Key</th><th>Value</th></tr></thead>"
            f"<tbody>{rows}</tbody></table></section>"
        )

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>{html.escape(title)}</title>
<style>
  body {{ font-family: system-ui, -apple-system, Segoe UI, Roboto, sans-serif; background: #0b1220; color: #e2e8f0; margin: 0; padding: 2rem; }}
  header {{ border-bottom: 1px solid #1e3a5f; padding-bottom: 1rem; margin-bottom: 2rem; }}
  h1 {{ color: #38bdf8; margin: 0 0 .35rem 0; }}
  .meta {{ color: #94a3b8; font-size: .9rem; }}
  .card {{ background: #111b2e; border: 1px solid #1e3a5f; border-radius: 10px; padding: 1.25rem; margin-bottom: 1.5rem; }}
  .card h2 {{ margin: 0 0 1rem 0; color: #7dd3fc; font-size: 1.15rem; display: flex; justify-content: space-between; align-items: center; }}
  .badge {{ background: #0c4a6e; color: #bae6fd; font-size: .78rem; padding: .2rem .55rem; border-radius: 999px; }}
  table {{ width: 100%; border-collapse: collapse; font-size: .9rem; }}
  th, td {{ text-align: left; padding: .45rem .65rem; border-bottom: 1px solid #1e293b; vertical-align: top; word-break: break-word; }}
  th {{ color: #38bdf8; background: #0f172a; }}
  td.k {{ color: #93c5fd; width: 32%; font-family: ui-monospace, Consolas, monospace; }}
  td.v {{ color: #f1f5f9; }}
</style>
</head>
<body>
  <header>
    <h1>{html.escape(title)}</h1>
    <div class="meta">Generated by VortexOSINT on {html.escape(now)} &bull; {len(sections)} source file(s)</div>
  </header>
  {"".join(cards_html)}
</body>
</html>
"""


def _render_md_report(sections: List[Dict[str, Any]], title: str) -> str:
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lines = [f"# {title}", "", f"_Generated by VortexOSINT on {now}_", ""]
    for sec in sections:
        lines.append(f"## {sec['source']}")
        lines.append("")
        lines.append("| Key | Value |")
        lines.append("| --- | --- |")
        for k, v in flatten_dict(sec["data"]).items():
            safe_k = str(k).replace("|", "\\|")
            safe_v = str(v).replace("|", "\\|").replace("\n", " ")
            lines.append(f"| `{safe_k}` | {safe_v} |")
        lines.append("")
    return "\n".join(lines)


def generate_report(input_files: List[str], output_path: str, title: str = "VortexOSINT Report") -> Dict[str, Any]:
    """Load one or more JSON files and write an HTML or Markdown report."""
    sections: List[Dict[str, Any]] = []
    for raw_path in input_files:
        p = Path(raw_path.strip())
        if not p.is_file():
            return {"error": f"Input file not found: {p}"}
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
        except Exception as e:
            return {"error": f"Invalid JSON in {p}: {e}"}
        sections.append({"source": p.name, "data": data})

    out = Path(output_path)
    if out.suffix.lower() in (".md", ".markdown"):
        content = _render_md_report(sections, title)
        fmt = "markdown"
    else:
        content = _render_html_report(sections, title)
        fmt = "html"

    out.write_text(content, encoding="utf-8")
    return {"output": str(out), "format": fmt, "sources": len(sections)}


def run(args: argparse.Namespace) -> int:
    """Run the Report generator module."""
    print_module_banner("REPORT", "HTML / Markdown Intelligence Report Generator")
    inp = getattr(args, "input", None)
    if not inp:
        print(f"{Colors.RED}[!] Specify --input <file1.json,file2.json>{Colors.RESET}")
        return 1

    files = [f.strip() for f in inp.split(",") if f.strip()]
    out_path = getattr(args, "output", None) or "vortexosint_report.html"
    title = getattr(args, "title", None) or "VortexOSINT Intelligence Report"

    res = generate_report(files, out_path, title=title)
    if res.get("error"):
        print(f"{Colors.RED}[!] {res['error']}{Colors.RESET}")
        return 1

    print(f"{Colors.GREEN}[+] {res['format'].upper()} report saved to {res['output']} ({res['sources']} source(s)){Colors.RESET}")
    return 0
